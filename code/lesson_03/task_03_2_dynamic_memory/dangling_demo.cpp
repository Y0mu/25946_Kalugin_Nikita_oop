// Отдельная маленькая программа для задания 3.II.
//
// Она делает ровно одну плохую вещь: читает память, которую уже освободили.
// В задании это нужно, чтобы "продемонстрировать опасность" висячего указателя.
// Запускается из main.cpp в отдельном процессе, чтобы падение не сломало
// остальную демонстрацию.
//
// Собрать отдельно:
//    g++ -std=c++17 -Wall -Wextra -O0 dangling_demo.cpp -o dangling_demo
//
// Ожидаемый результат: программа либо напечатает произвольное число,
// либо упадёт с нарушением доступа. Оба варианта — нормальное проявление
// неопределённого поведения.

#include <iostream>

// Чтобы не писать std:: перед каждым именем из стандартной библиотеки.
using namespace std;

int main() {
    // Захватываем память и что-то в неё кладём.
    int* pointer = new int{ 12345 };
    cout << "значение до удаления: " << *pointer << '\n';

    // Освобождаем память. Указатель не обнуляем — это и есть ошибка.
    delete pointer;

    // А теперь читаем по старому адресу. Так делать нельзя!
    int garbage = *pointer;
    cout << "значение после удаления: " << garbage << '\n';

    // И ещё раз записываем туда же — это уже порча чужой памяти.
    *pointer = 7;
    cout << "запись в освобождённую память выполнена\n";

    return 0;
}
