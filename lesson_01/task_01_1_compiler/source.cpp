// Задание 01.I. Компилятор.
// Это тот самый файл, который нужно собрать из командной строки.
// Здесь специально используются вещи, которые проверяются флагами компилятора:
//  - optional        -> нужен стандарт C++17
//  - #ifdef DEBUG_LOG     -> нужен макрос, заданный через /D или -D
//  - неиспользуемая переменная внутри #ifdef -> покажет, что предупреждения включены

#include <iostream>
#include <optional>

// Чтобы не писать std:: перед каждым именем из стандартной библиотеки.
using namespace std;

int main() {
    // Переменная, которая используется только в отладочном режиме.
    // Если собрать с /DDEBUG_LOG, то она пригодится, иначе компилятор
    // может сказать "unused variable" — как раз то, что нам нужно от /W4.
    int value = 0;

#ifdef DEBUG_LOG
    // Этот блок попадёт в код только если задан макрос DEBUG_LOG
    cout << "Debug mode\n";
    value = 42;
#endif

    // optional — это значение, которое может быть, а может и не быть.
    optional<int> number = 5;
    cout << "Number: " << *number << '\n';
    cout << "Value: " << value << '\n';

    return 0;
}
