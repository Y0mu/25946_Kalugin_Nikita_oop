#pragma once

// Задание 02.I. Аргументы функций.
// Задание 02.II. "Требуемая" функция с той же сигнатурой, что и модифицированная.
//
// Разбираем три способа передать аргументы:
//   1) по значению        SumByValue(int x, int y)        — копии, изменить снаружи нельзя
//   2) по ссылке          SumByLink(int& x, int& y)       — копий нет, изменения видны снаружи
//   3) по константной ссылке SumByConstLink(const int&, const int&)
//                                                         — копий нет, но менять нельзя
//
// Функции разложены по пространствам имён, потому что у "требуемой"
// и "модифицированной" функций сигнатуры одинаковые.

namespace required {

// Передача по значению: в функцию попадают копии, исходные переменные не меняются.
int SumByValue(int x, int y);

// Передача по ссылке: копий нет, и изменения аргументов видны снаружи функции.
// Именно это и требуется в задании 02.I.1.
int SumByLink(int& x, int& y);

// Передача по константной ссылке: копий нет (ссылка), но изменить значения нельзя.
// Это задание 02.I.2.
int SumByConstLink(const int& x, const int& y);

// Задание 02.II. "Требуемая" функция: сигнатура совпадает с модифицированной.
int Sum(int& x, int& y);

}  // namespace required

namespace modified {

// Задание 02.II. "Модифицированная" функция.
// Сигнатура такая же, как у required::Sum, но к результату
// в половине случаев добавляется случайное число.
int Sum(int& x, int& y);

}  // namespace modified
