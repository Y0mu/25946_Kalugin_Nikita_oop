// Дополнительный файл для темы "перегрузка функций" (слайды 4-7 лекции 02).
// Перегрузка — это когда у нескольких функций одно имя, но разные параметры.
// Различия могут быть:
//   - по количеству аргументов;
//   - по типам аргументов.
// Перегружать только по типу возвращаемого значения НЕЛЬЗЯ.

// Три аргумента вместо двух — это тоже перегрузка.
int Sum(int x, int y, int z);

// Другие типы аргументов.
double Sum(int x, double y);
double Sum(double x, int y);
double Sum(double x, double y);
