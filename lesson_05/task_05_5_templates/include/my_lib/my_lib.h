// Задание 5.V. Функции библиотеки стали шаблонными.
//
// Всё, что нужно знать про шаблоны в библиотеке:
//   * шаблонная функция не компилируется сама по себе — компилятор создаёт
//     нужный вариант тогда, когда видит конкретный вызов;
//   * поэтому реализацию шаблона пишут в заголовочном файле (иначе будет
//     ошибка линковки "unresolved external symbol");
//   * в библиотеке остаётся место и для обычных функций — например,
//     Version() реализована в my_lib.cpp.

namespace my_lib {

// ---- "Требуемая" функция ---------------------------------------------------
// T — тип аргументов И тип результата (как в лекции: template <typename T> T Sum(...)).
// Работает для любого типа, у которого определён оператор +.
template <typename T>
T Sum(const T& x, const T& y) {
    return x + y;
}

// Если типы аргументов разные, тип результата задаём первым параметром шаблона:
//   Sum<double, int, double>(3, 2.5) -> 5.5
template <typename TResult, typename T1, typename T2>
TResult Sum(const T1& x, const T2& y) {
    return static_cast<TResult>(x + y);
}

// Три аргумента — тоже шаблон, ничего особенного.
template <typename T>
T Sum(const T& x, const T& y, const T& z) {
    return x + y + z;
}

// ---- Обычная (не шаблонная) функция ---------------------------------------
// Она реализована в my_lib.cpp, поэтому у статической библиотеки действительно
// есть объектный файл, а не только заголовки.
int Version();

}  // namespace my_lib
